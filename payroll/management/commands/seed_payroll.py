"""
Seed reference data for development/demo.

    python manage.py seed_payroll
    python manage.py seed_payroll --demo --demo-password 'S0me-Long-Passw0rd!'
    python manage.py seed_payroll --tax-year 2027   # load next year's PAYE bands

`--tax-year` copies the bands of the most recent configured year (or the built-in
2026 bands if none exist). Review them against the law for that year before use.

IMPORTANT: the salary figures and allowance percentages below are ILLUSTRATIVE
placeholders generated by a formula so the system is runnable end-to-end.
Replace them with the official CONUASS / CONTISS tables and the institution's
approved allowance schedule before any real payroll run. The 2026 PAYE bands
follow the Nigeria Tax Act 2025.
"""
from datetime import date
from decimal import Decimal

from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction
from simple_history.utils import bulk_create_with_history

from accounts.models import Role
from payroll.models import AllowanceRule, SalaryScale, TaxBand
from staff.models import Department, Faculty, StaffProfile

User = get_user_model()

FACULTIES = [
    ("Arts", "ART"), ("Science", "SCI"), ("Education", "EDU"), ("Social Sciences", "SOC"),
    ("Law", "LAW"), ("Technology", "TEC"), ("Agriculture", "AGR"), ("Pharmacy", "PHA"),
    ("Veterinary Medicine", "VET"), ("Basic Medical Sciences", "BMS"), ("Clinical Sciences", "CLS"),
    ("Public Health", "PUH"), ("Dentistry", "DEN"), ("Multidisciplinary Studies", "MDS"),
]

# (annual base for step 1) per CONUASS level 1..7 - illustrative only
CONUASS_BASE = {1: 1_300_000, 2: 1_800_000, 3: 2_200_000, 4: 2_700_000, 5: 3_300_000, 6: 4_200_000, 7: 5_200_000}
CONUASS_STEPS = 9
CONTISS_LEVELS = range(1, 16)
CONTISS_STEPS = 9
STEP_INCREMENT = Decimal("0.025")  # +2.5% of step-1 base per step - illustrative only

# 2026 PAYE bands (Nigeria Tax Act 2025): (lower, upper, rate%)
TAX_BANDS_2026 = [
    (0, 800_000, 0), (800_000, 3_000_000, 15), (3_000_000, 12_000_000, 18),
    (12_000_000, 25_000_000, 21), (25_000_000, 50_000_000, 23), (50_000_000, None, 25),
]


class Command(BaseCommand):
    help = "Seed faculties, illustrative salary scales, allowance rules and 2026 PAYE bands."

    def add_arguments(self, parser):
        parser.add_argument("--demo", action="store_true", help="Also create a demo bursary officer and two staff members.")
        parser.add_argument("--demo-password", help="Password for demo accounts (required with --demo).")
        parser.add_argument(
            "--tax-year", type=int,
            help="Only create PAYE bands for this year (copied from the latest configured year), then exit.",
        )

    @transaction.atomic
    def handle(self, *args, **opts):
        if opts["demo"] and not opts["demo_password"]:
            raise CommandError("--demo requires --demo-password (no default password is ever used).")
        if opts["tax_year"]:
            self._seed_tax_year(opts["tax_year"])
            return

        for name, code in FACULTIES:
            Faculty.objects.get_or_create(code=code, defaults={"name": name})

        rows = []
        for level, base in CONUASS_BASE.items():
            for step in range(1, CONUASS_STEPS + 1):
                rows.append(("CONUASS", level, step, Decimal(base) * (1 + STEP_INCREMENT * (step - 1))))
        for level in CONTISS_LEVELS:
            base = Decimal(480_000 + (level - 1) * 250_000)
            for step in range(1, CONTISS_STEPS + 1):
                rows.append(("CONTISS", level, step, base * (1 + STEP_INCREMENT * (step - 1))))
        for scale, level, step, amount in rows:
            SalaryScale.objects.update_or_create(
                scale=scale, grade_level=level, step=step, defaults={"annual_basic": amount.quantize(Decimal("0.01"))}
            )

        if not AllowanceRule.objects.exists():
            bulk_create_with_history([  # keeps the audit trail complete
                AllowanceRule(allowance_type="HOUSING", calc_method="PERCENT_OF_BASIC", value=Decimal("25.00")),
                AllowanceRule(allowance_type="TRANSPORT", calc_method="PERCENT_OF_BASIC", value=Decimal("15.00")),
                AllowanceRule(allowance_type="RESEARCH", calc_method="PERCENT_OF_BASIC", value=Decimal("10.00"), employment_type="ACADEMIC"),
                AllowanceRule(allowance_type="MEDICAL", calc_method="FIXED_MONTHLY", value=Decimal("5000.00")),
            ], AllowanceRule)

        for lower, upper, rate in TAX_BANDS_2026:
            TaxBand.objects.update_or_create(
                tax_year=2026, lower_bound=Decimal(lower),
                defaults={"upper_bound": None if upper is None else Decimal(upper), "rate_percent": Decimal(rate)},
            )

        if opts["demo"]:
            self._demo(opts["demo_password"])

        self.stdout.write(self.style.SUCCESS("Seed complete. Salary figures are ILLUSTRATIVE - replace with official tables."))

    def _seed_tax_year(self, year):
        if TaxBand.objects.filter(tax_year=year).exists():
            self.stdout.write(self.style.WARNING(f"Tax bands for {year} already exist; nothing changed."))
            return
        source = TaxBand.objects.filter(tax_year__lt=year).order_by("-tax_year").values_list("tax_year", flat=True).first()
        if source:
            bands = [(b.lower_bound, b.upper_bound, b.rate_percent) for b in TaxBand.objects.filter(tax_year=source)]
            origin = f"copied from {source}"
        else:
            bands = [(Decimal(lo), None if hi is None else Decimal(hi), Decimal(r)) for lo, hi, r in TAX_BANDS_2026]
            origin = "from the built-in Nigeria Tax Act 2025 bands"
        bulk_create_with_history(
            [TaxBand(tax_year=year, lower_bound=lo, upper_bound=hi, rate_percent=rate) for lo, hi, rate in bands],
            TaxBand,
        )
        self.stdout.write(self.style.SUCCESS(
            f"Created {len(bands)} tax bands for {year} ({origin}). Verify them against the law for {year}."
        ))

    def _demo(self, password):
        faculty = Faculty.objects.get(code="SCI")
        dept, _ = Department.objects.get_or_create(faculty=faculty, code="CSC", defaults={"name": "Computer Science"})

        bursar, created = User.objects.get_or_create(
            username="bursar.demo", defaults={"email": "bursar.demo@example.edu.ng", "first_name": "Demo", "last_name": "Bursar", "role": Role.BURSARY}
        )
        if created:
            bursar.set_password(password)
            bursar.save()

        demo_staff = [
            ("lecturer.demo", "Ada", "Lecturer", "UI/ACAD/0001", "ACADEMIC", "CONUASS", 4, 3),
            ("officer.demo", "Tunde", "Officer", "UI/ADMIN/0001", "NON_ACADEMIC", "CONTISS", 8, 2),
        ]
        for username, first, last, staff_id, emp, scale, grade, step in demo_staff:
            user, created = User.objects.get_or_create(
                username=username, defaults={"email": f"{username}@example.edu.ng", "first_name": first, "last_name": last, "role": Role.STAFF}
            )
            if created:
                user.set_password(password)
                user.save()
            StaffProfile.objects.get_or_create(
                user=user,
                defaults=dict(
                    staff_id=staff_id, department=dept, employment_type=emp, salary_scale=scale,
                    grade_level=grade, step=step, date_of_employment=date(2018, 1, 15),
                    annual_rent_paid=Decimal("600000.00"), cooperative_monthly_dues=Decimal("10000.00"),
                ),
            )
